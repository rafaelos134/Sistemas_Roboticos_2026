"""Export a trained sumo policy as a single ROS 1 node for the psr-hero-kit.

    ~/ros2_ws/.venv/bin/python export_sumo.py runs/sumo_ppo_v1/best.pt exports/sumo/sumo_rl.py

The generated file follows kit/exercicios/sumo/sumo.py (same class, parameters and
topics) and respects the rules of the project (Section 3 of the statement):
one file, only standard Python + numpy + rospy + ROS messages + psr_hero.utils.
The actor network and the observation normalization are embedded in the file
(base64 float32) and evaluated with numpy; the critic is not needed to act.
Works on the kit ROS container (Python 3.8, numpy 1.17).
"""

from __future__ import annotations

import base64
import re
import sys
from pathlib import Path

import numpy as np
import torch

HERE = Path(__file__).resolve().parent


def numpy_block(path: Path) -> str:
    text = path.read_text()
    m = re.search(r"# >>> numpy-begin.*?\n(.*?)# <<< numpy-end", text, re.S)
    return m.group(1).rstrip() + "\n"


def b64(a) -> str:
    return base64.b64encode(np.ascontiguousarray(a, dtype="<f4").tobytes()).decode()


def wrap(s: str, width: int = 96) -> str:
    return "\n".join('    "%s"' % s[i:i + width] for i in range(0, len(s), width))


def export(ckpt_path: str, out_path: str) -> None:
    ck = torch.load(ckpt_path, map_location="cpu", weights_only=False)
    sd = ck["model"]
    linears = sorted({k.rsplit(".", 1)[0] for k in sd if k.startswith("actor.") and k.endswith(".weight")},
                     key=lambda k: int(k.split(".")[1]))
    arrays = [("norm_mean", sd["norm.mean"].numpy()), ("norm_var", sd["norm.var"].numpy())]
    for j, name in enumerate(linears):
        arrays.append(("W%d" % j, sd[name + ".weight"].numpy()))
        arrays.append(("b%d" % j, sd[name + ".bias"].numpy()))
    weights = "\n".join(
        "    %r: (%r, (\n%s\n    )),"
        % (name, tuple(a.shape), wrap(b64(a))) for name, a in arrays
    )
    cfg = ck.get("config", {})
    info = "run %s, iteration %s, training win rate %.1f%%" % (
        Path(ckpt_path).parent.name, ck.get("iter"), 100.0 * ck.get("win", 0.0))
    src = TEMPLATE.replace("@@INFO@@", info)
    src = src.replace("@@N_LAYERS@@", str(len(linears)))
    src = src.replace("@@CONTROL_HZ@@", str(round(1.0 / cfg.get("control_dt", 0.05))))
    src = src.replace("@@OBS@@", numpy_block(HERE / "sumo_obs.py"))
    src = src.replace("@@WEIGHTS@@", weights)
    out = Path(out_path)
    out.write_text(src)
    out.chmod(0o777)
    print("wrote %s (%.0f kB): %s" % (out, out.stat().st_size / 1024, info))


TEMPLATE = r'''#!/usr/bin/env python3
"""Sumo with a policy trained by reinforcement learning (PPO).

Generated by rl/export_sumo.py (@@INFO@@).
Do not edit by hand: train again and export. Documentation: rl/docs/documentacao.md

Same interface as the template kit/exercicios/sumo/sumo.py:
  parameters  ~robot (own id), ~opponent (opponent id)
  subscribes  /hero_<robot>/odom, /hero_<opponent>/odom, /game/state
  publishes   /hero_<robot>/cmd_vel

The actor network (MLP 12 -> 64 -> 64 -> 2, tanh) is embedded below and runs with
numpy. Its input is the observation of observation_np() (everything in the robot's
own frame, so the same file works as hero_0 or hero_1); its output, clipped to
[-1, 1], is scaled to (V_MAX, W_MAX). Only standard Python, numpy, rospy, the ROS
messages and psr_hero.utils are used, as the rules of the project require.

Run:  ./run.sh run sumo robot0:=sumo_rl.py robot1:=none
"""
import base64
import json
import math

import numpy as np
import rospy
from geometry_msgs.msg import Twist
from nav_msgs.msg import Odometry
from std_msgs.msg import String

from psr_hero.utils import V_MAX, W_MAX, pose_from_odom

RING_R = 0.40
CONTROL_HZ = @@CONTROL_HZ@@  # the rate the policy was trained at


# --- observation (copied from rl/sumo_obs.py) ---------------------------------
@@OBS@@

# --- actor network ------------------------------------------------------------------------
WEIGHTS = {
@@WEIGHTS@@
}


def _load(name):
    shape, chunks = WEIGHTS[name]
    return np.frombuffer(base64.b64decode("".join(chunks)), dtype="<f4").reshape(shape).astype(np.float64)


class Policy:
    """Deterministic actor: the mean of the Gaussian policy, without sampling."""

    def __init__(self):
        self.mean = _load("norm_mean")
        self.std = np.sqrt(_load("norm_var") + 1e-5)
        self.layers = [(_load("W%d" % j), _load("b%d" % j)) for j in range(@@N_LAYERS@@)]

    def __call__(self, obs):
        x = np.clip((np.asarray(obs, dtype=np.float64) - self.mean) / self.std, -5.0, 5.0)
        for j, (w, b) in enumerate(self.layers):
            x = w.dot(x) + b
            if j < len(self.layers) - 1:
                x = np.tanh(x)
        return np.clip(x, -1.0, 1.0)


class Sumo:
    def __init__(self):
        rospy.init_node("sumo")
        self.robot = rospy.get_param("~robot", 0)
        self.opponent = rospy.get_param("~opponent", 1)
        self.me = None  # (x, y, yaw)
        self.speed = 0.0  # own forward speed, m/s
        self.w = 0.0  # own angular speed, rad/s
        self.opp = None  # (x, y, yaw)
        self.opp_speed = 0.0
        self.opp_w = 0.0
        self.prev_action = (0.0, 0.0)
        self.round_time = None
        self.policy = Policy()

        self.pub = rospy.Publisher("/hero_%d/cmd_vel" % self.robot, Twist, queue_size=1)
        rospy.Subscriber("/hero_%d/odom" % self.robot, Odometry, self.on_me, queue_size=1)
        rospy.Subscriber("/hero_%d/odom" % self.opponent, Odometry, self.on_opp, queue_size=1)
        rospy.Subscriber("/game/state", String, self.on_game, queue_size=1)

    def on_me(self, msg):
        self.me = pose_from_odom(msg)
        self.speed = msg.twist.twist.linear.x
        self.w = msg.twist.twist.angular.z

    def on_opp(self, msg):
        self.opp = pose_from_odom(msg)
        self.opp_speed = msg.twist.twist.linear.x
        self.opp_w = msg.twist.twist.angular.z

    def on_game(self, msg):
        # a new round started (the robots went back to the start): the policy was
        # trained with a zero previous action at the start of every round
        try:
            t = float(json.loads(msg.data).get("round_time", 0.0))
        except (ValueError, TypeError, AttributeError):
            return
        if self.round_time is not None and t < self.round_time - 0.5:
            self.prev_action = (0.0, 0.0)
        self.round_time = t

    def compute_command(self, me, opp, speed, now):
        """The trained policy: (linear_x, angular_z) from the two poses and speeds."""
        obs = observation_np((me[0], me[1], me[2], speed, self.w),
                             (opp[0], opp[1], opp[2], self.opp_speed, self.opp_w), self.prev_action)
        a = self.policy(obs)
        self.prev_action = (float(a[0]), float(a[1]))
        return float(a[0]) * V_MAX, float(a[1]) * W_MAX

    def run(self):
        rate = rospy.Rate(CONTROL_HZ)
        while not rospy.is_shutdown():
            if self.me is None or self.opp is None:
                rospy.logwarn_throttle(2.0, "waiting for odometry")
            else:
                v, w = self.compute_command(self.me, self.opp, self.speed, rospy.get_time())
                cmd = Twist()
                cmd.linear.x, cmd.angular.z = v, w
                self.pub.publish(cmd)
            rate.sleep()


if __name__ == "__main__":
    Sumo().run()
'''


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    export(sys.argv[1], sys.argv[2])
