def b64(a):
    return base64.b64encode(np.ascontiguousarray(a, dtype="<f4").tobytes()).decode()


def net_arrays(prefix, ckpt):
    sd = torch.load(ckpt, map_location="cpu", weights_only=False)["model"]
    names = sorted({k.rsplit(".", 1)[0] for k in sd if k.startswith("actor.") and k.endswith(".weight")},
                   key=lambda k: int(k.split(".")[1]))
    arr = [(prefix + "norm_mean", sd["norm.mean"].numpy()), (prefix + "norm_var", sd["norm.var"].numpy())]
    for j, n in enumerate(names):
        arr += [(prefix + "W%d" % j, sd[n + ".weight"].numpy()), (prefix + "b%d" % j, sd[n + ".bias"].numpy())]
    return arr, len(names)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--att", required=True)
    p.add_argument("--def", dest="defender", default=None)
    p.add_argument("--out", required=True)
    p.add_argument("--no-unjam", action="store_true", help="pure network, without the rule-based jam supervisor")
    p.add_argument("--fusion", action="store_true", help="estimate the state with soccer_fusion.py (noisy sensors)")
    args = p.parse_args()

    arrays, n_att = net_arrays("att_", args.att)
    n_def = 0
    if args.defender:
        a, n_def = net_arrays("def_", args.defender)
        arrays += a
    weights = "\n".join("    %r: (%r, (\n%s\n    ))," % (n, tuple(a.shape), wrap(b64(a))) for n, a in arrays)
    info = "attackers: %s%s%s%s" % (Path(args.att).parent.name, "" if args.no_unjam else " + unjam rules",
                                  " + odometry/lidar fusion" if args.fusion else "",
                                ("; defender: %s" % Path(args.defender).parent.name) if args.defender else "; keeper: script")
    src = (TEMPLATE.replace("@@INFO@@", info).replace("@@N_ATT@@", str(n_att)).replace("@@N_DEF@@", str(n_def))
           .replace("@@OBS@@", numpy_block(HERE / "soccer_obs.py")).replace("@@WEIGHTS@@", weights).replace("@@UNJAM@@", str(not args.no_unjam))
           .replace("@@FUSION@@", str(args.fusion))
           .replace("@@FUSBLOCK@@", numpy_block(HERE / "soccer_fusion.py") if args.fusion else "# (not exported)\n"))
    out = Path(args.out)
    out.write_text(src)
    out.chmod(0o777)
    print("wrote %s (%.0f kB): %s" % (out, out.stat().st_size / 1024, info))


