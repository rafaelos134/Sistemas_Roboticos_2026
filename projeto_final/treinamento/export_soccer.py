def _load(name):
    shape, chunks = WEIGHTS[name]
    return np.frombuffer(base64.b64decode("".join(chunks)), dtype="<f4").reshape(shape).astype(np.float64)


class Policy:
    """Deterministic actor (mean of the Gaussian policy)."""

    def __init__(self, prefix, n_layers):
        self.mean = _load(prefix + "norm_mean")
        self.std = np.sqrt(_load(prefix + "norm_var") + 1e-5)
        self.layers = [(_load(prefix + "W%d" % j), _load(prefix + "b%d" % j)) for j in range(n_layers)]

    def __call__(self, obs):
        x = np.clip((np.asarray(obs, dtype=np.float64) - self.mean) / self.std, -5.0, 5.0)
        for j, (w, b) in enumerate(self.layers):
            x = w.dot(x) + b
            if j < len(self.layers) - 1:
                x = np.tanh(x)
        return np.clip(x, -1.0, 1.0)


def keeper_script(me, ball):
    """Scripted keeper (team frame): goal line, y = ball y clipped to the goal mouth."""
    ty = clamp(ball[1], -GOAL_HALF + 0.03, GOAL_HALF - 0.03)
    dx, dy = (-HALF_L + 0.07) - me[0], ty - me[1]
    if math.hypot(dx, dy) < 0.03:
        return 0.0, clamp(4.0 * wrap_angle(math.atan2(ball[1] - me[1], ball[0] - me[0]) - me[2]), -W_MAX, W_MAX)
    err = wrap_angle(math.atan2(dy, dx) - me[2])
    return (V_MAX if abs(err) < 0.5 else 0.0), clamp(4.0 * err, -W_MAX, W_MAX)


def go_to(me, tx, ty):
    err = wrap_angle(math.atan2(ty - me[1], tx - me[0]) - me[2])
    return (V_MAX if abs(err) < 0.5 else 0.0), clamp(4.0 * err, -W_MAX, W_MAX)


def push_to(me, ball, gx, gy, behind=0.08):
    """Get behind the ball on the line ball -> (gx, gy) and push it there (team frame)."""
    ux, uy = gx - ball[0], gy - ball[1]
    d = max(math.hypot(ux, uy), 1e-6)
    ux, uy = ux / d, uy / d
    bx, by = ball[0] - behind * ux, ball[1] - behind * uy
    rx, ry = ball[0] - me[0], ball[1] - me[1]
    along, cross = rx * ux + ry * uy, -rx * uy + ry * ux
    if along > 0.02 and abs(cross) < 0.035:
        tx, ty = ball[0] + 0.10 * ux, ball[1] + 0.10 * uy
    elif along < 0:
        side = -1.0 if cross > 0 else 1.0
        tx, ty = bx + side * 0.09 * -uy, by + side * 0.09 * ux
    else:
        tx, ty = bx, by
    return go_to(me, clamp(tx, -HALF_L + 0.04, HALF_L - 0.04), clamp(ty, -HALF_W + 0.04, HALF_W - 0.04))


class Unjam:
    """Rule-based supervisor on top of the attacker network (hybrid controller).

    A jam = the ball moved less than JAM_DIST in JAM_S seconds (it happens against the walls,
    where the network gets stuck and nothing in the game resets it). Then, for MANEUVER_S
    seconds, the attacker closest to the ball pushes it ALONG the wall, towards the opponent
    side and away from the corner, and the other one lines up behind it and pushes too (two
    against one); after that the network takes over again (COOLDOWN_S before a new maneuver)."""

    JAM_S, JAM_DIST, MANEUVER_S, COOLDOWN_S = 3.0, 0.03, 2.5, 2.0

    def __init__(self):
        self.ref, self.t_ref, self.until, self.ready_at, self.target = None, 0.0, -1.0, 0.0, None

    def update(self, ball, now):
        """ball in the team frame. Returns the push target (x, y) while a maneuver is active, else None."""
        if self.ref is None or math.hypot(ball[0] - self.ref[0], ball[1] - self.ref[1]) > self.JAM_DIST:
            self.ref, self.t_ref = (ball[0], ball[1]), now
        if now < self.until:
            return self.target
        if now - self.t_ref > self.JAM_S and now >= self.ready_at:
            # along the nearest wall, towards +x (their side); in a corner of their side, towards the goal
            tx, ty = clamp(ball[0] + 0.35, -HALF_L + 0.1, HALF_L - 0.1), ball[1]
            if abs(ball[1]) < HALF_W - 0.08 and abs(ball[0]) > HALF_L - 0.08:  # against an end wall
                ty = 0.0
                tx = ball[0] + (0.3 if ball[0] < 0 else -0.05)
            elif ball[0] > HALF_L - 0.25:  # long wall near their goal: towards the goal mouth
                tx, ty = HALF_L, 0.0
            self.target = (tx, ty)
            self.until, self.ready_at = now + self.MANEUVER_S, now + self.MANEUVER_S + self.COOLDOWN_S
            self.ref, self.t_ref = (ball[0], ball[1]), now
            return self.target
        return None


