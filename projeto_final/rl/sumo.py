def _load(name):
    shape, chunks = WEIGHTS[name]
    return np.frombuffer(base64.b64decode("".join(chunks)), dtype="<f4").reshape(shape).astype(np.float64)


class Policy:
    """Deterministic actor: the mean of the Gaussian policy, without sampling."""

    def __init__(self):
        self.mean = _load("norm_mean")
        self.std = np.sqrt(_load("norm_var") + 1e-5)
        self.layers = [(_load("W%d" % j), _load("b%d" % j)) for j in range(3)]

    def __call__(self, obs):
        x = np.clip((np.asarray(obs, dtype=np.float64) - self.mean) / self.std, -5.0, 5.0)
        for j, (w, b) in enumerate(self.layers):
            x = w.dot(x) + b
            if j < len(self.layers) - 1:
                x = np.tanh(x)
        return np.clip(x, -1.0, 1.0)


# --- telemetria para os logs do torneio ---------------------------------------
# A cada TEL_PERIOD s (relógio do ROS) escreve no log uma linha "TEL {json}" com a
# posição de todos os robôs, bola/bandeiras, estado do jogo e o comando enviado.
# Mudanças de placar/estado do jogo saem na hora como "EVT {json}", e os parâmetros
# do nó saem uma vez como "TELINIT {json}". Os logs aparecem em api/log do site
# do torneio. Isso só gera log: o comportamento do robô continua igual.
TIPO = "rl"
TEL_PERIOD = 1.0  # s entre linhas TEL; 0 desliga (site guarda ~400 linhas)
TEL_IGNORAR = ("field", "ring_radius", "base_x", "base_radius")  # constantes: não vão para o log
TEL_RELOGIO = ("t", "time", "round_time", "held", "message")  # não disparam EVT (vêm junto de placar/tags)


def _tel_r(p, n=3):
    """Arredonda (x, y[, yaw, ...]) para caber no log; None continua None."""
    if p is None:
        return None
    return [round(float(x), n) for x in p]


class Telemetria:
    def __init__(self, period=TEL_PERIOD):
        self.period, self.last, self.ultimo_jogo, self.t0 = period, -1e9, None, None
        self.init, self.eventos = None, True  # eventos=False: este nó não escreve EVT

    @staticmethod
    def _log(tag, campos):
        try:
            rospy.loginfo("%s %s", tag, json.dumps(campos, separators=(",", ":")))
        except Exception as e:  # nunca derrubar o nó por causa do log
            rospy.logwarn_throttle(10.0, "telemetria: %s" % e)

    def inicio(self, eventos=True, **campos):
        self.init, self.eventos = campos, eventos

    def __call__(self, now, game=None, **campos):
        if self.period <= 0:
            return
        if self.t0 is None:
            self.t0 = now
            if self.init is not None:
                self._log("TELINIT", self.init)
        t = round(now - self.t0, 2)  # s desde o início do nó
        game = {k: v for k, v in (game or {}).items() if k not in TEL_IGNORAR}
        chave = json.dumps({k: v for k, v in game.items() if k not in TEL_RELOGIO}, sort_keys=True)
        if self.eventos and self.ultimo_jogo is not None and chave != self.ultimo_jogo:
            self._log("EVT", dict(t=t, jogo=game))
        self.ultimo_jogo = chave
        if now - self.last < self.period:
            return
        self.last = now
        self._log("TEL", dict(t=t, jogo=game, **campos))


class Sumo:
    def __init__(self):
        rospy.init_node("sumo")
        self.robot = rospy.get_param("~robot", 0)
        self.opponent = rospy.get_param("~opponent", 1)
        self.me = None  # (x, y, yaw)
        self.speed = 0.0  # own forward speed, m/s
        self.w = 0.0  # own angular speed, rad/s
        self.opp = None  # (x, y, yaw)
        self.opp_speed = 0.0
        self.opp_w = 0.0
        self.prev_action = (0.0, 0.0)
        self.round_time = None
        self.policy = Policy()
        self.game = {}  # último /game/state (telemetria)
        self.tel = Telemetria()
        self.tel.inicio(jogo="sumo", tipo=TIPO, robot=self.robot, opponent=self.opponent)

        self.pub = rospy.Publisher("/hero_%d/cmd_vel" % self.robot, Twist, queue_size=1)
        rospy.Subscriber("/hero_%d/odom" % self.robot, Odometry, self.on_me, queue_size=1)
        rospy.Subscriber("/hero_%d/odom" % self.opponent, Odometry, self.on_opp, queue_size=1)
        rospy.Subscriber("/game/state", String, self.on_game, queue_size=1)

    def on_me(self, msg):
        self.me = pose_from_odom(msg)
        self.speed = msg.twist.twist.linear.x
        self.w = msg.twist.twist.angular.z

    def on_opp(self, msg):
        self.opp = pose_from_odom(msg)
        self.opp_speed = msg.twist.twist.linear.x
        self.opp_w = msg.twist.twist.angular.z

    def on_game(self, msg):
        try:
            self.game = json.loads(msg.data)
        except (ValueError, TypeError):
            pass
        # a new round started (the robots went back to the start): the policy was
        # trained with a zero previous action at the start of every round
        try:
            t = float(json.loads(msg.data).get("round_time", 0.0))
        except (ValueError, TypeError, AttributeError):
            return
        if self.round_time is not None and t < self.round_time - 0.5:
            self.prev_action = (0.0, 0.0)
        self.round_time = t

    def compute_command(self, me, opp, speed, now):
        """The trained policy: (linear_x, angular_z) from the two poses and speeds."""
        obs = observation_np((me[0], me[1], me[2], speed, self.w),
                             (opp[0], opp[1], opp[2], self.opp_speed, self.opp_w), self.prev_action)
        a = self.policy(obs)
        self.prev_action = (float(a[0]), float(a[1]))
        return float(a[0]) * V_MAX, float(a[1]) * W_MAX

    def run(self):
        rate = rospy.Rate(CONTROL_HZ)
        while not rospy.is_shutdown():
            if self.me is None or self.opp is None:
                rospy.logwarn_throttle(2.0, "waiting for odometry")
            else:
                v, w = self.compute_command(self.me, self.opp, self.speed, rospy.get_time())
                cmd = Twist()
                cmd.linear.x, cmd.angular.z = v, w
                self.pub.publish(cmd)
                self.tel(rospy.get_time(), self.game,
                         me=_tel_r(tuple(self.me) + (self.speed, self.w)),
                         opp=_tel_r(tuple(self.opp) + (self.opp_speed, self.opp_w)),
                         cmd=_tel_r((v, w)))
            rate.sleep()


if __name__ == "__main__":
    Sumo().run()
